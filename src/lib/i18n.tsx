type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window === "undefined") return "it";
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === "it" || saved === "en") return saved;
    return navigator.language.toLowerCase().startsWith("en") ? "en" : "it";
  });

  useEffect(() => {
    document.documentElement.lang = language;
    window.localStorage.setItem(STORAGE_KEY, language);
  }, [language]);

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      setLanguage: setLanguageState,
      t: (key, values) => {
        const translation = dictionaries[language][key] ?? dictionaries.it[key] ?? key;
        return typeof translation === "function" ? translation(values) : translation;
      },
    }),
    [language],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

// eslint-disable-next-line react-refresh/only-export-components
export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

export function categoryLabelKey(category: string) {
  const keys: Record<string, string> = {
    musica: "categoryMusica",
    sport: "categorySport",
    social: "categorySocial",
    cultura: "categoryCultura",
    food: "categoryFood",
    nightlife: "categoryNightlife",
  };
  return keys[category] ?? "categorySocial";
}
